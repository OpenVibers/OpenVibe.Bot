-- phase: expand
-- Agent Streams S7 (design 2026-11-06, AGENT-STREAMS-S7-REACH-DESIGN §6): the robot commands an agent drives through
-- Bot, as steps. When an agent stream's agent drives a robot, each command appears on the stream beside the desk
-- ("Drive forward 1 m": passed). Bot keeps the command itself and the stream the agent named, so the harness (or a
-- reader of the steps) can see what the robot did; chat never writes here through S5 or S6, and Bot's gate, audit and
-- kill switch are unchanged.
--
-- Expand only: every table is new and an older release ignores it.
CREATE TABLE IF NOT EXISTS robot_agent_steps (
    id             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    robot_id       text COLLATE "C" NOT NULL,
    subject_id     text COLLATE "C",
    agent_stream_id text COLLATE "C",
    kind           text COLLATE "C" NOT NULL,
    title          text COLLATE "C" NOT NULL,
    status         text COLLATE "C" NOT NULL CHECK (status IN ('passed', 'failed', 'refused')),
    reason         text COLLATE "C",
    value          jsonb,
    at             timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS robot_agent_steps_robot ON robot_agent_steps (robot_id, at DESC, id DESC);
CREATE INDEX IF NOT EXISTS robot_agent_steps_stream ON robot_agent_steps (agent_stream_id, at DESC) WHERE agent_stream_id IS NOT NULL;
